"""Русские названия классов техники и согласование числительных.

Нужно, чтобы карточка отклонения читалась как "1 экскаватор", "2 самосвала",
"5 самосвалов" — формулировка на русском языке, которую поймёт прораб
(docs/01-principles.md, правило 5), а не англоязычный код класса.
"""
from __future__ import annotations

# (единственное, "мало" 2-4, "много" 0/5+) — стандартное русское согласование.
CLASS_RU: dict[str, tuple[str, str, str]] = {
    "excavator": ("экскаватор", "экскаватора", "экскаваторов"),
    "dump_truck": ("самосвал", "самосвала", "самосвалов"),
    "concrete_mixer": ("автобетоносмеситель", "автобетоносмесителя", "автобетоносмесителей"),
    "concrete_pump": ("бетононасос", "бетононасоса", "бетононасосов"),
    "tower_crane": ("башенный кран", "башенных крана", "башенных кранов"),
    "mobile_crane": ("автокран", "автокрана", "автокранов"),
    "bulldozer": ("бульдозер", "бульдозера", "бульдозеров"),
    "roller": ("каток", "катка", "катков"),
    "loader": ("погрузчик", "погрузчика", "погрузчиков"),
    "drilling_rig": ("буровая установка", "буровых установки", "буровых установок"),
}

# Русские синонимы классов — для нечёткого сопоставления колонок ресурсов
# в исходном графике (см. schedule_io.py).
CLASS_RU_SYNONYMS: dict[str, list[str]] = {
    "excavator": ["экскаватор"],
    "dump_truck": ["самосвал", "самосвалы"],
    "concrete_mixer": ["автобетоносмеситель", "миксер", "бетоносмеситель"],
    "concrete_pump": ["бетононасос"],
    "tower_crane": ["башенный кран", "башенный"],
    "mobile_crane": ["автокран"],
    "bulldozer": ["бульдозер"],
    "roller": ["каток"],
    "loader": ["погрузчик"],
    "drilling_rig": ["буровая установка", "буровая"],
}


def ru_word(cls: str, n: int) -> str:
    """Форма названия класса, согласованная с числом `n`."""
    one, few, many = CLASS_RU.get(cls, (cls, cls, cls))
    mod10, mod100 = n % 10, n % 100
    if mod10 == 1 and mod100 != 11:
        return one
    if 2 <= mod10 <= 4 and not (12 <= mod100 <= 14):
        return few
    return many


def ru_count(n: int, cls: str) -> str:
    """"1 экскаватор", "2 самосвала", "5 самосвалов"."""
    return f"{n} {ru_word(cls, n)}"


def ru_count_list(counts: dict[str, int]) -> str:
    """"1 экскаватор, 2 самосвала" — по классам, отсортировано по имени класса."""
    parts = [ru_count(n, cls) for cls, n in sorted(counts.items()) if n > 0]
    return ", ".join(parts) if parts else "техники нет"
